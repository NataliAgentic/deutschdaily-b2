// DeutschDaily B2 — frontend logic.
// Loads the dictionary from /api/words, renders today's 5, search, and favorites.

const FAV_KEY = 'deutschdaily_favorites_v1';
const DAILY_COUNT = 5;

let allWords = [];
let dailyWords = [];   // today's 5 (deterministic by date)
let extraShuffled = []; // extra random sets generated by the Shuffle button

// ---------- Boot ----------
document.addEventListener('DOMContentLoaded', async () => {
  renderToday();
  try {
    const res = await fetch('/api/words');
    if (!res.ok) throw new Error('Failed to load dictionary');
    allWords = await res.json();
  } catch (err) {
    document.getElementById('dailyCards').innerHTML =
      '<p class="empty-state">Could not load the dictionary. Please refresh.</p>';
    console.error(err);
    return;
  }

  dailyWords = pickDaily(allWords, DAILY_COUNT);
  renderCards('dailyCards', dailyWords);
  renderFavorites();
  wireEvents();
});

// ---------- Today label ----------
function renderToday() {
  const date = new Date();
  const formatted = date.toLocaleDateString('en-US', {
    weekday: 'long', year: 'numeric', month: 'long', day: 'numeric'
  });
  document.getElementById('todayLabel').textContent = formatted;
}

// ---------- Daily 5 (deterministic by date) ----------
function todaySeed() {
  const d = new Date();
  const ymd = `${d.getFullYear()}-${d.getMonth() + 1}-${d.getDate()}`;
  return hashString(ymd);
}

function hashString(str) {
  let h = 0;
  for (let i = 0; i < str.length; i++) {
    h = (h * 31 + str.charCodeAt(i)) | 0;
  }
  return h >>> 0;
}

// mulberry32 — small, fast, good-enough seeded PRNG.
function mulberry32(seed) {
  return function () {
    let t = (seed += 0x6D2B79F5);
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function seededShuffle(arr, seed) {
  const random = mulberry32(seed);
  const out = arr.slice();
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

function pickDaily(words, n) {
  return seededShuffle(words, todaySeed()).slice(0, n);
}

// ---------- Card rendering ----------
function renderCards(containerId, items) {
  const container = document.getElementById(containerId);
  if (!items.length) {
    container.innerHTML = '';
    return;
  }
  container.innerHTML = items.map(cardHTML).join('');
  // Wire star buttons in this container.
  container.querySelectorAll('.star-btn').forEach(btn => {
    btn.addEventListener('click', () => {
      const german = btn.dataset.key;
      toggleFavorite(german);
      // Re-render every section so star states stay consistent.
      renderCards('dailyCards', dailyWords);
      if (extraShuffled.length) renderCards('searchCards', extraShuffled);
      renderFavorites();
    });
  });
}

function cardHTML(w) {
  const fav = isFavorite(w.german);
  const articleHTML = w.article ? `<span class="card-article">${w.article}</span>` : '';
  return `
    <article class="card">
      <button class="star-btn" type="button" aria-pressed="${fav}" data-key="${escapeAttr(w.german)}" title="${fav ? 'Remove from favorites' : 'Save to favorites'}">
        ${starSVG(fav)}
      </button>
      <p class="card-pos">${w.partOfSpeech}</p>
      <h3 class="card-german">${articleHTML}<span>${escapeHTML(w.german)}</span></h3>
      <p class="card-english">${escapeHTML(w.english)}</p>
      <div class="card-example">
        <div>${escapeHTML(w.example)}</div>
        <div class="card-example-en">${escapeHTML(w.exampleTranslation)}</div>
      </div>
    </article>
  `;
}

function starSVG(filled) {
  if (filled) {
    return '<svg viewBox="0 0 24 24" fill="currentColor" aria-hidden="true"><path d="M12 2.5l2.95 6.36 6.99.65-5.27 4.78 1.55 6.86L12 17.77l-6.22 3.38 1.55-6.86L2.06 9.51l6.99-.65L12 2.5z"/></svg>';
  }
  return '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" aria-hidden="true"><path d="M12 3.5l2.7 5.82 6.4.6-4.83 4.38 1.42 6.28L12 17.4l-5.69 3.18 1.42-6.28L2.9 9.92l6.4-.6L12 3.5z" stroke-linejoin="round"/></svg>';
}

// ---------- Search ----------
function wireEvents() {
  const input = document.getElementById('searchInput');
  const button = document.getElementById('searchBtn');
  const shuffleBtn = document.getElementById('shuffleBtn');
  const clearFavBtn = document.getElementById('clearFavBtn');

  button.addEventListener('click', runSearch);
  input.addEventListener('keydown', e => {
    if (e.key === 'Enter') runSearch();
  });
  shuffleBtn.addEventListener('click', () => {
    extraShuffled = pickExtraRandom(DAILY_COUNT);
    renderCards('searchCards', extraShuffled);
    document.getElementById('searchStatus').textContent =
      `Here are ${DAILY_COUNT} more random B2 words to study.`;
    document.getElementById('searchInput').value = '';
  });
  clearFavBtn.addEventListener('click', () => {
    if (!confirm('Remove all favorites?')) return;
    saveFavorites([]);
    renderFavorites();
    // Refresh other sections so stars update.
    renderCards('dailyCards', dailyWords);
    if (extraShuffled.length) renderCards('searchCards', extraShuffled);
  });
}

function pickExtraRandom(n) {
  const dailyKeys = new Set(dailyWords.map(w => w.german));
  const pool = allWords.filter(w => !dailyKeys.has(w.german));
  // Plain Math.random shuffle — non-deterministic on purpose.
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  return pool.slice(0, n);
}

function runSearch() {
  const q = document.getElementById('searchInput').value.trim().toLowerCase();
  const status = document.getElementById('searchStatus');

  if (!q) {
    status.textContent = '';
    extraShuffled = [];
    renderCards('searchCards', []);
    return;
  }

  const matches = allWords.filter(w => {
    const englishMeanings = w.english.toLowerCase().split(',').map(s => s.trim());
    if (englishMeanings.some(m => m === q)) return true;
    if (englishMeanings.some(m => m.includes(q))) return true;
    if (w.german.toLowerCase().includes(q)) return true;
    return false;
  });

  if (matches.length > 0) {
    extraShuffled = matches;
    renderCards('searchCards', matches);
    status.textContent = `Found ${matches.length} match${matches.length === 1 ? '' : 'es'} for "${q}".`;
  } else {
    // Fallback — show 3 random B2 words so the user still learns something.
    const fallback = pickRandom(allWords, 3);
    extraShuffled = fallback;
    renderCards('searchCards', fallback);
    status.textContent =
      `No match for "${q}" in our B2 dictionary. Here are 3 B2 words you might enjoy instead.`;
  }
}

function pickRandom(arr, n) {
  const copy = arr.slice();
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy.slice(0, n);
}

// ---------- Favorites (localStorage) ----------
function loadFavorites() {
  try {
    const raw = localStorage.getItem(FAV_KEY);
    return raw ? JSON.parse(raw) : [];
  } catch {
    return [];
  }
}
function saveFavorites(list) {
  localStorage.setItem(FAV_KEY, JSON.stringify(list));
}
function isFavorite(german) {
  return loadFavorites().includes(german);
}
function toggleFavorite(german) {
  const list = loadFavorites();
  const idx = list.indexOf(german);
  if (idx === -1) list.push(german);
  else list.splice(idx, 1);
  saveFavorites(list);
}
function renderFavorites() {
  const favKeys = loadFavorites();
  const empty = document.getElementById('favEmpty');
  const clearBtn = document.getElementById('clearFavBtn');
  const favWords = allWords.filter(w => favKeys.includes(w.german));

  if (favWords.length === 0) {
    document.getElementById('favCards').innerHTML = '';
    empty.hidden = false;
    clearBtn.hidden = true;
  } else {
    empty.hidden = true;
    clearBtn.hidden = false;
    renderCards('favCards', favWords);
  }
}

// ---------- Tiny escape helpers ----------
function escapeHTML(str) {
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
function escapeAttr(str) {
  return escapeHTML(str);
}
